// Optional helper: build symmetric rows from left halves (not used at load time,
// handy for anyone adding new art).
function mirror(halfRows) {
  return halfRows.map(function (r) { return r + r.split('').reverse().join(''); });
}

const _spriteCache = {};
const _spriteWarned = {};
const _palRGB = {};

function _hexToRGB(hex) {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function _paletteRGB(palName) {
  if (!_palRGB[palName]) _palRGB[palName] = PAL[palName].map(_hexToRGB);
  return _palRGB[palName];
}

function getSprite(name, palName) {
  const key = name + '|' + (palName || '');
  const hit = _spriteCache[key];
  if (hit) return hit;
  const def = SPRITES[name];
  const c = document.createElement('canvas');
  if (!def) {
    if (!_spriteWarned[name]) {
      _spriteWarned[name] = true;
      console.warn('getSprite: unknown sprite "' + name + '"');
    }
    c.width = 16; c.height = 16;
    const x = c.getContext('2d');
    x.fillStyle = '#ff00ff';
    x.fillRect(0, 0, 16, 16);
    _spriteCache[key] = c;
    return c;
  }
  let pn = palName || def.pal;
  if (!PAL[pn]) {
    const wk = 'pal:' + pn;
    if (!_spriteWarned[wk]) {
      _spriteWarned[wk] = true;
      console.warn('getSprite: unknown palette "' + pn + '" (sprite "' + name + '")');
    }
    pn = def.pal;
  }
  c.width = def.w; c.height = def.h;
  const ctx = c.getContext('2d');
  if (!PAL[pn]) {
    ctx.fillStyle = '#ff00ff';
    ctx.fillRect(0, 0, def.w, def.h);
    _spriteCache[key] = c;
    return c;
  }
  const rgb = _paletteRGB(pn);
  const img = ctx.createImageData(def.w, def.h);
  const d = img.data;
  for (let y = 0; y < def.h; y++) {
    const row = def.rows[y] || '';
    for (let x = 0; x < def.w; x++) {
      const ch = row.charCodeAt(x) - 49; // '1' -> 0
      if (ch < 0 || ch > 2) continue;
      const col = rgb[ch];
      const i = (y * def.w + x) * 4;
      d[i] = col[0]; d[i + 1] = col[1]; d[i + 2] = col[2]; d[i + 3] = 255;
    }
  }
  ctx.putImageData(img, 0, 0);
  _spriteCache[key] = c;
  return c;
}
